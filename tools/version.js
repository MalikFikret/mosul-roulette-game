// Writes src/ui/version.js: the game version (package.json "version") and the short git commit
// of HEAD, for the About page. Plain Node, no dependencies. If git is not available (or this is
// not a git checkout), the commit is null and the page shows the version alone.
//
// Usage (project root): npm run version:write
// Run it whenever package.json "version" changes, and before publishing a new build. The commit
// it records is the HEAD at the time it runs, i.e. the commit the build is based on (a commit
// cannot contain its own hash).

import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = new URL('../', import.meta.url);
const OUT = new URL('src/ui/version.js', root);

const { version } = JSON.parse(readFileSync(new URL('package.json', root), 'utf8'));
if (typeof version !== 'string' || !/^\d+\.\d+\.\d+$/.test(version)) {
  throw new Error(`package.json "version" must look like 1.2.3, got ${JSON.stringify(version)}`);
}

function shortCommit() {
  try {
    const out = execFileSync('git', ['rev-parse', '--short', 'HEAD'], {
      cwd: fileURLToPath(root),
      encoding: 'utf8',
      stdio: ['ignore', 'pipe', 'ignore'],
    }).trim();
    return /^[0-9a-f]{4,40}$/.test(out) ? out : null;
  } catch {
    return null;
  }
}

const commit = shortCommit();
const text = `// GENERATED by \`npm run version:write\` (tools/version.js). Do not edit by hand.
export const VERSION = ${JSON.stringify(version)};
export const COMMIT = ${JSON.stringify(commit)};
`;
writeFileSync(OUT, text);
console.log(`src/ui/version.js: ${version}${commit ? ` (${commit})` : ''}`);
